"""Tests for turning observation pairs into transfer verdicts.

The numbers here are hand-computed rather than generated by the code under
test. A comparison function that is only ever checked against itself will
happily agree with a wrong formula, so every case states the expected value
in the assertion.
"""

from __future__ import annotations

import numpy as np
import pytest
from app.evaluation.base import ClassificationObservation, EmbeddingObservation
from app.evaluation.comparison import compare, compare_classification, compare_embedding


def classification(
    top1_index: int,
    top1_probability: float,
    *,
    label: str = "alpha",
    entropy: float = 1.0,
    top5: list[tuple[int, float]] | None = None,
) -> ClassificationObservation:
    return ClassificationObservation(
        top1_index=top1_index,
        top1_label=label,
        top1_probability=top1_probability,
        top1_logit=0.0,
        top5=top5 if top5 is not None else [(top1_index, top1_probability)],
        entropy=entropy,
    )


def embedding(vector: np.ndarray, similarities: dict[str, float], ranking: list[str]):
    return EmbeddingObservation(
        embedding=vector.astype(np.float32),
        text_similarities=similarities,
        text_ranking=ranking,
    )


# -- classification ---------------------------------------------------------


def test_confidence_drop_is_signed_correctly():
    row = compare_classification(classification(1, 0.9), classification(2, 0.1))
    assert row["confidence_drop"] == pytest.approx(0.8)
    assert row["relative_drop"] == pytest.approx(0.8 / 0.9)


def test_a_confidence_increase_reports_a_negative_drop():
    row = compare_classification(classification(1, 0.2), classification(1, 0.6))
    assert row["confidence_drop"] == pytest.approx(-0.4)
    assert row["relative_drop"] == pytest.approx(-2.0)


def test_label_change_is_reported():
    row = compare_classification(classification(1, 0.9), classification(2, 0.1))
    assert row["label_changed"] is True


def test_target_disrupted_requires_both_a_label_change_and_a_75pct_drop():
    # Label changed, drop is only 50%: not disrupted.
    assert (
        compare_classification(
            classification(1, 0.8), classification(2, 0.4)
        )["target_disrupted"]
        is False
    )
    # No label change, huge drop: not disrupted either.
    assert (
        compare_classification(
            classification(1, 0.8), classification(1, 0.1)
        )["target_disrupted"]
        is False
    )
    # Both: disrupted.
    assert (
        compare_classification(
            classification(1, 0.8), classification(2, 0.1)
        )["target_disrupted"]
        is True
    )


def test_relative_drop_is_none_when_the_original_confidence_is_zero():
    row = compare_classification(classification(1, 0.0), classification(2, 0.0))
    assert row["relative_drop"] is None
    # And such a row can never claim a disruption.
    assert row["target_disrupted"] is False


def test_relative_drop_distinguishes_a_fluke_from_a_success():
    """A 90% drop from 0.02 is not the same event as from 0.80."""
    small = compare_classification(classification(1, 0.02), classification(2, 0.002))
    large = compare_classification(classification(1, 0.80), classification(2, 0.08))
    assert small["confidence_drop"] < large["confidence_drop"]
    assert small["relative_drop"] == pytest.approx(large["relative_drop"])


def test_top5_overlap_counts_shared_labels():
    original = classification(
        1, 0.5, top5=[(1, 0.5), (2, 0.2), (3, 0.1), (4, 0.1), (5, 0.1)]
    )
    protected = classification(
        2, 0.4, top5=[(2, 0.4), (1, 0.2), (9, 0.1), (8, 0.1), (7, 0.1)]
    )
    row = compare_classification(original, protected)
    assert row["top5_overlap"] == pytest.approx(0.4)


def test_entropy_rise_reports_spreading():
    original = classification(1, 0.9, entropy=0.5)
    protected = classification(2, 0.1, entropy=2.0)
    row = compare_classification(original, protected)
    assert row["entropy_rise"] == pytest.approx(1.5)


def test_confidence_collapse_does_not_require_a_label_change():
    """The real failure mode: the model stops believing, the argmax survives.

    A CW attack that flattens the distribution usually leaves the same class on
    top. Counting only label flips would report this as a failed attack.
    """
    row = compare_classification(classification(1, 0.8), classification(1, 0.1))
    assert row["label_changed"] is False
    assert row["confidence_collapsed"] is True
    assert row["target_disrupted"] is False


def test_collapse_is_reported_at_seventy_five_percent():
    assert compare_classification(
        classification(1, 0.8), classification(1, 0.2)
    )["confidence_collapsed"] is True
    assert compare_classification(
        classification(1, 0.8), classification(1, 0.21)
    )["confidence_collapsed"] is False


# -- embedding --------------------------------------------------------------


def test_identical_embeddings_have_cosine_one():
    vector = np.array([1.0, 0.0, 0.0])
    row = compare_embedding(
        embedding(vector, {"a": 0.5}, ["a"]), embedding(vector, {"a": 0.5}, ["a"])
    )
    assert row["cosine_similarity"] == pytest.approx(1.0)
    assert row["embedding_l2"] == pytest.approx(0.0)
    assert row["best_prompt_changed"] is False


def test_orthogonal_embeddings_have_cosine_zero():
    row = compare_embedding(
        embedding(np.array([1.0, 0.0]), {"a": 0.5}, ["a"]),
        embedding(np.array([0.0, 1.0]), {"a": 0.5}, ["a"]),
    )
    assert row["cosine_similarity"] == pytest.approx(0.0)
    assert row["embedding_l2"] == pytest.approx(np.sqrt(2.0))


def test_opposite_embeddings_have_cosine_minus_one():
    row = compare_embedding(
        embedding(np.array([1.0, 0.0]), {"a": 0.5}, ["a"]),
        embedding(np.array([-1.0, 0.0]), {"a": 0.5}, ["a"]),
    )
    assert row["cosine_similarity"] == pytest.approx(-1.0)


def test_text_similarity_deltas_are_per_prompt():
    row = compare_embedding(
        embedding(
            np.array([1.0, 0.0]), {"a dog": 0.30, "a car": 0.20}, ["a dog", "a car"]
        ),
        embedding(
            np.array([1.0, 0.0]), {"a dog": 0.20, "a car": 0.25}, ["a car", "a dog"]
        ),
    )
    assert row["text_similarity_deltas"]["a dog"] == pytest.approx(-0.10)
    assert row["text_similarity_deltas"]["a car"] == pytest.approx(0.05)
    assert row["best_prompt_changed"] is True


def test_text_regression_counts_top_prompts_that_lost_ground():
    row = compare_embedding(
        embedding(
            np.array([1.0, 0.0]),
            {"a": 0.40, "b": 0.30, "c": 0.10},
            ["a", "b", "c"],
        ),
        embedding(
            np.array([1.0, 0.0]),
            {"a": 0.20, "b": 0.25, "c": 0.40},
            ["c", "b", "a"],
        ),
    )
    # 'a' and 'b' were originally top-2 and both dropped.
    assert row["text_regression_count"] == 2


def test_text_regression_ignores_prompts_that_were_never_competitive():
    """A deep-ranked prompt losing ground is not a regression of the reading.

    Only the original top two were competing for the answer, so a loss on
    "d" in fourth place must not be reported.
    """
    row = compare_embedding(
        embedding(
            np.array([1.0, 0.0]),
            {"a": 0.40, "b": 0.30, "c": 0.20, "d": 0.05},
            ["a", "b", "c", "d"],
        ),
        embedding(
            np.array([1.0, 0.0]),
            {"a": 0.42, "b": 0.31, "c": 0.21, "d": 0.02},
            ["a", "b", "c", "d"],
        ),
    )
    assert row["text_similarity_deltas"]["d"] == pytest.approx(-0.03)
    assert row["text_regression_count"] == 0


def test_rank_deltas_report_promotions_and_demotions():
    row = compare_embedding(
        embedding(np.array([1.0, 0.0]), {"a": 0.4, "b": 0.3}, ["a", "b"]),
        embedding(np.array([1.0, 0.0]), {"a": 0.3, "b": 0.4}, ["b", "a"]),
    )
    assert row["rank_deltas"]["a"] == 1  # demoted
    assert row["rank_deltas"]["b"] == -1  # promoted


# -- dispatch ---------------------------------------------------------------


def test_compare_dispatches_by_family():
    row = compare(
        classification(1, 0.5), classification(2, 0.1)
    )
    assert "relative_drop" in row


def test_compare_rejects_mixed_families():
    with pytest.raises(TypeError, match="Mismatched observation families"):
        compare(
            classification(1, 0.5),
            embedding(np.array([1.0]), {"a": 0.5}, ["a"]),
        )


def _verdict(*, collapsed: bool, disrupted: bool, relative: float | None) -> dict:
    """A comparison row reduced to the fields transfer_summary reads."""
    return {
        "confidence_collapsed": collapsed,
        "target_disrupted": disrupted,
        "label_changed": disrupted,
        "relative_drop": relative,
    }


ROLES = {
    "resnet18": "target",
    "densenet121": "surrogate",
    "vit_b_16": "held_out",
    "swin_t": "held_out",
    "clip_vit_b_32": "evaluator",
}


def test_transfer_rate_is_computed_over_held_out_models_only():
    """The headline must not be diluted by the models that were paid for.

    All four optimised-against models collapsing and neither transformer moving
    is a complete optimisation failure that a mixed average would score at 60%.
    """
    from app.evaluation.comparison import transfer_summary

    comparisons = {
        "resnet18": _verdict(collapsed=True, disrupted=True, relative=0.9),
        "densenet121": _verdict(collapsed=True, disrupted=False, relative=0.8),
        "vit_b_16": _verdict(collapsed=False, disrupted=False, relative=0.1),
        "swin_t": _verdict(collapsed=False, disrupted=False, relative=0.05),
    }
    summary = transfer_summary(comparisons, dict(ROLES))

    assert summary["ensemble_transfer_success"] == 0.0
    assert summary["ensemble_transfer_success_strict"] == 0.0
    assert summary["surrogates"]["collapse_rate"] == 1.0
    assert summary["held_out"]["evaluated"] == 2
    assert summary["held_out"]["expected"] == 2
    assert summary["held_out_complete"] is True


def test_transfer_rate_is_none_when_no_held_out_model_ran():
    """Zero success and "measured nothing" must not look the same."""
    from app.evaluation.comparison import transfer_summary

    summary = transfer_summary(
        {"resnet18": _verdict(collapsed=True, disrupted=True, relative=0.9)},
        dict(ROLES),
    )
    assert summary["ensemble_transfer_success"] is None
    assert summary["held_out"]["evaluated"] == 0
    assert summary["held_out_complete"] is False
    assert sorted(summary["held_out"]["not_evaluated"]) == ["swin_t", "vit_b_16"]


def test_a_roleless_model_is_never_counted_as_held_out_evidence():
    """A model with no declared role must not count as evidence.

    It belongs to neither bucket, so it must not silently inflate the rate the
    report is graded against.
    """
    from app.evaluation.comparison import transfer_summary

    summary = transfer_summary(
        {"mystery": _verdict(collapsed=True, disrupted=True, relative=0.99)},
        dict(ROLES),
    )
    assert summary["ensemble_transfer_success"] is None
    assert summary["unassigned"]["evaluated"] == 1
    assert summary["held_out"]["evaluated"] == 0


def test_held_out_status_reports_every_declared_model():
    """Coverage has to be visible per model, not just as a count."""
    from app.evaluation.comparison import transfer_summary

    summary = transfer_summary(
        {"vit_b_16": _verdict(collapsed=True, disrupted=False, relative=0.8)},
        dict(ROLES),
        evaluated={"vit_b_16": "ok", "swin_t": "skipped", "resnet18": "ok"},
    )
    assert summary["held_out_status"] == {"swin_t": "skipped", "vit_b_16": "ok"}
    assert summary["held_out_complete"] is False


def test_evaluator_and_target_rows_are_kept_separate():
    """CLIP and ResNet-18 must stay in their own buckets.

    Neither belongs in the surrogate or the held-out bucket, and putting either
    there would change the headline rate.
    """
    from app.evaluation.comparison import transfer_summary

    summary = transfer_summary(
        {
            "resnet18": _verdict(collapsed=True, disrupted=True, relative=0.9),
            "clip_vit_b_32": _verdict(collapsed=False, disrupted=False, relative=0.02),
            "vit_b_16": _verdict(collapsed=True, disrupted=True, relative=0.8),
        },
        dict(ROLES),
    )
    assert summary["target"]["evaluated"] == 1
    assert summary["evaluator"]["evaluated"] == 1
    assert summary["held_out"]["evaluated"] == 1
    assert summary["surrogates"]["evaluated"] == 0
    assert summary["ensemble_transfer_success"] == 1.0

def test_evaluator_transfer_uses_clip_own_evidence():
    """CLIP has no confidence to collapse, so its rate must come from prompts.

    Reusing the classification counters here would report 0% success for a probe
    that changed its best answer outright, which is backwards.
    """
    from app.evaluation.comparison import transfer_summary

    original = embedding(
        np.array([1.0, 0.0]), {"a": 0.9, "b": 0.8, "c": 0.7}, ["a", "b", "c"]
    )
    protected = embedding(
        np.array([0.0, 1.0]), {"a": 0.2, "b": 0.9, "c": 0.1}, ["b", "a", "c"]
    )
    row = compare_embedding(original, protected)
    assert row["best_prompt_changed"] is True

    summary = transfer_summary({"clip_vit_b_32": row}, dict(ROLES))
    assert summary["embedding"]["evaluated"] == 1
    assert summary["evaluator_transfer_success"] == 1.0
    assert summary["ensemble_transfer_success"] is None
    assert summary["evaluator_complete"] is True
    assert summary["held_out_complete"] is False

# -- face ---------------------------------------------------------------


def face(
    detected: bool = True,
    confidence: float | None = 1.0,
    box: tuple[int, int, int, int] | None = None,
    vector: np.ndarray | None = None,
    reason: str = "",
):
    from app.evaluation.base import FaceObservation

    return FaceObservation(
        detected=detected,
        confidence=confidence,
        box=box,
        embedding=None if vector is None else vector.astype(np.float32),
        reason=reason,
    )


def detections(*items: tuple[str, float, tuple[int, int, int, int]]):
    from app.evaluation.base import Detection, DetectionObservation

    return DetectionObservation(
        detections=[
            Detection(label=label, confidence=confidence, box=box)
            for label, confidence, box in items
        ]
    )


def text(answers: dict[str, str], model: str = "vlm", reason: str = ""):
    from app.evaluation.base import TextObservation

    return TextObservation(answers=answers, model=model, reason=reason)


def test_face_detection_failure_does_not_invent_an_identity_score():
    """A vanished face must report no descriptor, not a convenient default."""
    from app.evaluation.comparison import compare_face

    original = face(box=(10, 10, 60, 70), vector=np.array([1.0, 0.0]))
    protected = face(detected=False, confidence=None, box=None, reason="no face")

    row = compare_face(original, protected)
    assert row["face_lost"] is True
    assert row["face_embedding_cosine"] is None
    assert row["face_identity_preserved"] is None
    assert row["box_iou"] is None
    assert row["reason"] == "no face"


def test_face_identity_can_rotate_while_the_box_stays_put():
    """The detector passes and the recognition fails; both must be visible."""
    from app.evaluation.comparison import compare_face

    box = (10, 10, 60, 70)
    row = compare_face(
        face(box=box, vector=np.array([1.0, 0.0])),
        face(box=box, vector=np.array([0.0, 1.0])),
    )
    assert row["face_lost"] is False
    assert row["box_iou"] == pytest.approx(1.0)
    assert row["box_center_shift"] == pytest.approx(0.0)
    assert row["face_embedding_cosine"] == pytest.approx(0.0)
    assert row["face_identity_preserved"] is False


def test_face_identity_is_preserved_for_an_identical_descriptor():
    from app.evaluation.comparison import compare_face

    vector = np.array([0.6, 0.8])
    original = face(box=(0, 0, 10, 10), vector=vector)
    row = compare_face(original, face(box=(0, 0, 10, 10), vector=vector))
    assert row["face_embedding_cosine"] == pytest.approx(1.0)
    assert row["face_embedding_l2"] == pytest.approx(0.0, abs=1e-6)
    assert row["face_identity_preserved"] is True


def test_face_box_shift_is_reported_in_pixels():
    """A small box moves the same distance as a large one, so pixels tell."""
    from app.evaluation.comparison import compare_face

    row = compare_face(
        face(box=(10, 20, 60, 70)), face(box=(30, 20, 80, 70))
    )
    assert row["box_center_shift"] == pytest.approx(20.0)
    assert row["box_iou"] < 1.0


def test_detection_loss_is_counted_separately_from_label_change():
    from app.evaluation.comparison import compare_detection

    original = detections(("person", 0.9, (0, 0, 10, 10)), ("tie", 0.6, (5, 5, 6, 6)))
    protected = detections(("person", 0.9, (0, 0, 10, 10)))

    row = compare_detection(original, protected)
    assert row["detection_count_delta"] == -1
    assert row["detection_lost_labels"] == ["tie"]
    assert row["detection_labels_changed"] is True
    assert row["detection_matched"] == 1
    assert row["detection_match_rate"] == pytest.approx(0.5)
    assert row["detection_confidence_delta"] == pytest.approx(0.0)


def test_detection_confidence_drops_without_losing_the_object():
    """Lower confidence is a weaker effect than losing the box, and differs."""
    from app.evaluation.comparison import compare_detection

    original = detections(("person", 0.9, (0, 0, 10, 10)))
    protected = detections(("person", 0.4, (0, 0, 10, 10)))

    row = compare_detection(original, protected)
    assert row["detection_count_delta"] == 0
    assert row["detection_labels_changed"] is False
    assert row["detection_match_rate"] == pytest.approx(1.0)
    assert row["detection_confidence_delta"] == pytest.approx(-0.5)


def test_text_comparison_normalises_case_and_whitespace_only():
    """Case and spacing are noise; punctuation and wording are the answer."""
    from app.evaluation.comparison import compare_text

    same = compare_text(
        text({"q": "A man   in a suit"}), text({"q": "a man in a suit"})
    )
    assert same["text_answers_changed"] is False
    assert same["text_answers_changed_count"] == 0

    different = compare_text(
        text({"q": "A man in a suit"}), text({"q": "a woman in a dress"})
    )
    assert different["text_answers_changed"] is True
    assert different["text_changed_prompts"] == ["q"]


def test_text_comparison_reports_per_prompt_changes():
    from app.evaluation.comparison import compare_text

    row = compare_text(
        text({"a": "cat", "b": "dog", "c": "sky"}),
        text({"a": "cat", "b": "wolf", "c": "sky"}),
    )
    assert row["text_answers_total"] == 3
    assert row["text_answers_changed_count"] == 1
    assert row["text_changed_prompts"] == ["b"]


# -- summary across families -------------------------------------------


def test_probe_rows_never_reach_the_classification_headline():
    """Face and detection evidence is real, but it has no confidence to drop.

    Folding a face row into the held-out bucket would count it as a non-collapse
    and drag the transfer rate down by a number that means nothing.
    """
    from app.evaluation.comparison import transfer_summary

    roles = {"vit_b_16": "held_out", "mtcnn": "held_out", "resnet18": "surrogate"}
    families = {"vit_b_16": "classification", "mtcnn": "face"}
    summary = transfer_summary(
        {
            "vit_b_16": _verdict(collapsed=True, disrupted=True, relative=0.9),
            "mtcnn": {"face_lost": True, "face_detected": False},
            "resnet18": _verdict(collapsed=True, disrupted=True, relative=0.99),
        },
        roles,
        families=families,
    )
    assert summary["held_out"]["evaluated"] == 1
    assert summary["ensemble_transfer_success"] == 1.0
    assert summary["face"]["evaluated"] == 1
    assert summary["face"]["faces_lost"] == 1


def test_held_out_completeness_counts_only_classifiers():
    """A declared face model in the held-out set must not make it incomplete."""
    from app.evaluation.comparison import transfer_summary

